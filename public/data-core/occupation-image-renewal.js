export function renewedCareerImage(id, slug) {
  if (!careerImageScenes[id]) return {};
  const stem = `/data-core/assets/roadmap/covers/v2/${id}-${slug}-v2`;
  return {
    asset: `${stem}.webp`,
    sourceAsset: `${stem}-detail.webp`,
    detailAsset: `${stem}-detail.webp`,
    detailWidth: 1440, detailHeight: 1080,
    version: '20260919-work-v2',
    alt: careerImageScenes[id],
    visualFocus: careerImageScenes[id],
    concept: careerImageScenes[id],
  };
}
