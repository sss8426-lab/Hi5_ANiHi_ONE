// Editorial modes, independent of the existing search/homefeed title strategy.
export function blogWritingGuide(mode: unknown): string {
  const selected = mode === 'aeo' || mode === 'geo' ? mode : 'seo';
  const guides = {
    seo: 'SEO 작성 방식: 검색한 독자의 의도와 선택 기준을 해결하세요. 제목·소제목·본문·사진 설명을 한 주제로 연결하고 핵심 정보를 텍스트로 제공하세요. 키워드 밀도나 반복 횟수를 목표로 하지 말고, 지역명만 바꾼 유사 글을 만들지 마세요.',
    aeo: 'AEO 작성 방식: 핵심 질문에 첫 문단에서 직접 답하고 이유·조건·방법·예외 순서로 설명하세요. 실제 질문에 맞는 질문형 소제목을 선택하고 바로 아래 답하세요. FAQ는 해결되지 않은 실제 질문이 있을 때만 쓰세요. 질문 변형을 반복하거나 답을 끝까지 숨기지 마세요.',
    geo: 'GEO 작성 방식: 검증 가능한 사실과 맥락을 중심으로 설명하세요. 숫자는 학년도·대상·단위·분모와 제공된 원문 출처를 주장 가까이에 표시하세요. 사실·교사의 해석·운영 가설을 구분하고 확인된 경험만 연결하세요. 출처 URL·통계·확인일을 만들지 말고, 근거가 없으면 주장을 제외하고 missingInfo에 남기세요. AI 인용을 보장하지 마세요.',
  };
  return [
    `이번 요청의 작성 방식은 ${selected.toUpperCase()}입니다. 다음 기준이 기존 양식의 분량·키워드 횟수·질문형 소제목 강제 규칙보다 우선합니다.`,
    guides[selected],
    '공통: 키워드 반복 횟수나 밀도를 목표로 삼지 마세요. 제목의 약속에 본문이 답해야 합니다. 홈피드형 제목을 선택해도 실제 고민과 확인된 변화만 다루고 낚시성 제목·가짜 경험은 금지합니다. 글자 수·사진 수·소제목 수를 채우려고 반복하지 마세요. FAQ·표·요약은 필요할 때만 사용하세요.',
    '캠퍼스·브랜드·연락처를 섞지 마세요. 학생 발언·수상·합격·수업료·시간표·효과·순위·검색량을 추측하지 마세요. 개인정보·작품 사용 동의는 사진만 보고 확인됐다고 하지 마세요. 생성 이미지를 실제 수업 증거로 설명하지 마세요.',
    '외부 자료는 입력으로 제공된 출처만 연결하세요. 자료 발행일·기준 학년도·실제 확인일을 혼동하지 마세요. 출처가 필요한 수치와 사례가 없으면 본문에서 제외하고 missingInfo에 사실·출처·사용 권한 확인 필요 및 발행 보류 사유를 기록하세요. 내부 검수 메모는 lead·body·cta에 넣지 마세요.',
    '기존 JSON 응답 형식을 유지하세요. strategy에는 독자 상황과 핵심 질문·목적을, titles에는 검색형·홈피드형 후보를, lead/body에는 공개 원고를, missingInfo에는 별도 검수 항목을 담으세요. 공식 SEO 점수·노출 확률을 계산하거나 네이버 블로그에 robots.txt·JSON-LD·llms.txt를 적용하라고 하지 마세요.',
  ].join('\n');
}
