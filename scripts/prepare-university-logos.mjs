import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
const {default:sharp}=await import(process.env.SHARP_MODULE||'sharp');
const source='outputs/university-logo-source', destination='public/data-core/assets/university-logos';
await fs.mkdir(destination,{recursive:true});
const manifest=[];
for(const name of (await fs.readdir(source)).sort()){
  if(!/\.(png|jpe?g|gif|webp)$/i.test(name))continue;
  const title=path.parse(name).name.replace(/(?:[ _-]*(?:로고|엠블럼|logo|emblem))$/i,'').trim();
  const bytes=await fs.readFile(path.join(source,name));
  const id=createHash('sha256').update(bytes).digest('hex').slice(0,16);
  const filename=`${id}.webp`;
  await sharp(bytes).resize({width:440,height:200,fit:'inside',withoutEnlargement:true}).webp({quality:92}).toFile(path.join(destination,filename));
  manifest.push({name:title,campus:'',src:`/data-core/assets/university-logos/${filename}`,alt:`${title} 로고`,title,role:'university-identity'});
}
await fs.writeFile('public/data-core/university-logo-manifest.js',`// Generated by scripts/prepare-university-logos.mjs from the supplied archive.\nexport const universityLogos = ${JSON.stringify(manifest,null,2)};\n`);
console.log(JSON.stringify({files:manifest.length,uniqueAssets:new Set(manifest.map(m=>m.src)).size}));
