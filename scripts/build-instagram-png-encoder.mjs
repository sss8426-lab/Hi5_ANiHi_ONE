import {build} from 'esbuild';
import {readFile,writeFile} from 'node:fs/promises';
// Bundle the existing locked codec, not a new image service or browser-specific PNG encoder.
await build({stdin:{contents:"export {encode} from 'fast-png';",resolveDir:process.cwd()},bundle:true,format:'esm',platform:'browser',minify:true,
  banner:{js:'/* fast-png 8.0.0 browser encoder; see FAST-PNG-LICENSES.txt. Generated by scripts/build-instagram-png-encoder.mjs. */'},
  outfile:'public/data-core/vendor/fast-png-8.0.0-encoder.js'});
const licenses=[];
for(const name of ['fast-png','fflate','iobuffer']){
  const pkg=JSON.parse(await readFile(`node_modules/${name}/package.json`,'utf8'));
  licenses.push(`${name} ${pkg.version}\n${await readFile(`node_modules/${name}/LICENSE`,'utf8')}`);
}
await writeFile('public/data-core/vendor/FAST-PNG-LICENSES.txt',licenses.join('\n\n'));
