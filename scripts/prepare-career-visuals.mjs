import fs from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {occupationImageConcepts} from '../public/data-core/occupation-image-concepts.js';
import {editorial, sections, titles, commonStyle, commonAvoid} from './career-visual-editorial.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const assetRoot = path.join(root, 'public/data-core/assets/roadmap/detail');
const publicRoot = path.join(root, 'public');
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const slugFor = id => {
  const concept = occupationImageConcepts.find(item => item.occupationId === id);
  if (!concept) throw Error(`Unknown occupation ${id}`);
  return concept.slug;
};

export async function buildVisuals() {
  const context = {window:{}};
  vm.runInNewContext(await fs.readFile(path.join(publicRoot, 'data-core/roadmap-content.js'), 'utf8'), context);
  const careers = context.window.HI5_ROADMAP_CONTENT.careers;
  const ids = editorial.map(row => row[0]);
  if (new Set(ids).size !== careers.length || ids.length !== careers.length || careers.some(c => !ids.includes(c.id))) throw Error('Career visual ID coverage mismatch');
  const data = {}, prompts = {}, missing = [];
  for (const [id, ...rows] of editorial) {
    if (rows.length !== 3) throw Error(`Three sections required for ${id}`);
    const slug = slugFor(id);
    const career = careers.find(c => c.id === id);
    data[id] = {};
    prompts[id] = {slug, name:career.name, sections:{}};
    for (const [i, [intro, pairs, scene, alt]] of rows.entries()) {
      const section = sections[i], filename = section === 'competencies' ? 'competency' : section;
      const image = `/data-core/assets/roadmap/detail/${slug}/${filename}.webp`;
      const width = 1600, height = i === 2 ? 1200 : 1000;
      let bytes;
      try { bytes = await fs.readFile(path.join(publicRoot, image)); }
      catch (error) { if (error.code !== 'ENOENT') throw error; missing.push(`${id}/${filename}`); }
      data[id][section] = {title:titles[i], intro, items:pairs.map(([title,description]) => ({title,description})), image, imageAlt:alt, width, height, version:bytes ? sha(bytes).slice(0,12) : 'pending', available:Boolean(bytes)};
      prompts[id].sections[section] = {
        image, scene, subjects:[career.name, i === 0 ? '수업·연습 과정' : i === 1 ? '비교·수정 과정' : '완성 포트폴리오'],
        props:pairs.map(pair => pair[0]), avoid:commonAvoid,
        prompt:`Generate ONE ${width}x${height} landscape educational photograph. Career: ${career.name} (${slug}). Purpose: ${titles[i]}. ${scene} ${commonStyle}`,
        provenance:'Generated fictional educational example; not actual student work, an admissions requirement or a promised outcome.',
      };
    }
  }
  const source = '// Generated by scripts/prepare-career-visuals.mjs; edit scripts/career-visual-editorial.mjs.\n'
    + `window.HI5_CAREER_VISUAL_CONTENT = ${JSON.stringify(data,null,2)};\n`
    + 'for (const career of window.HI5_ROADMAP_CONTENT?.careers || []) {\n  career.visualContent = window.HI5_CAREER_VISUAL_CONTENT[career.id];\n}\n';
  return {data, prompts:{schemaVersion:1, commonStyle, careers:prompts}, source, missing};
}

async function main() {
  const [mode, id, section, source, replaceHash] = process.argv.slice(2);
  if (mode === '--image') {
    if (!editorial.some(row => row[0] === id) || !['learning','competency','portfolio'].includes(section)) throw Error('Unknown image target');
    if (!source || !path.isAbsolute(source)) throw Error('Generated image source must be absolute');
    const directory = path.join(assetRoot, slugFor(id));
    await fs.mkdir(directory,{recursive:true});
    const destination = path.join(directory, `${section}.webp`);
    if (replaceHash) {
      if (!/^[a-f0-9]{64}$/.test(replaceHash) || sha(await fs.readFile(destination)) !== replaceHash) throw Error('Replacement requires the exact current image SHA256');
    } else {
      try { await fs.access(destination); throw Error('Refusing to overwrite an existing approved image'); }
      catch (error) { if (error.code !== 'ENOENT') throw error; }
    }
    const {default:sharp} = await import('sharp');
    const height = section === 'portfolio' ? 1200 : 1000;
    let bytes;
    for (const quality of [82,78,74,70]) {
      bytes = await sharp(source).rotate().resize(1600,height,{fit:'contain',background:'#f8faf9'}).webp({quality,effort:5}).toBuffer();
      if (bytes.length <= 350*1024) break;
    }
    await fs.writeFile(destination, bytes, {flag:replaceHash ? 'w' : 'wx'});
    console.log(JSON.stringify({id,section,bytes:bytes.length,path:path.relative(root,destination)}));
  } else if (mode && mode !== '--check') throw Error('Use --image ID learning|competency|portfolio absolute-source, --check, or no arguments');
  const result = await buildVisuals();
  if (mode === '--check') {
    if (result.missing.length) throw Error(`Missing ${result.missing.length} assets: ${result.missing.join(', ')}`);
    const current = await fs.readFile(path.join(publicRoot,'data-core/career-visual-content.js'),'utf8');
    if (current.replaceAll('\r\n','\n') !== result.source) throw Error('Generated visual content is stale');
    const manifest = JSON.parse(await fs.readFile(path.join(publicRoot,'data-core/career-visual-prompts.json'),'utf8'));
    if (JSON.stringify(manifest) !== JSON.stringify(result.prompts)) throw Error('Prompt manifest is stale');
  } else {
    await fs.writeFile(path.join(publicRoot,'data-core/career-visual-content.js'), result.source);
    await fs.writeFile(path.join(publicRoot,'data-core/career-visual-prompts.json'), JSON.stringify(result.prompts,null,2)+'\n');
  }
  console.log(JSON.stringify({careers:editorial.length,images:105-result.missing.length,missing:result.missing.length}));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
